// Printable booking receipt, built only from contract fields of a BOOKED request.
// Opens a new tab with a clean page; the user can print or "Save as PDF".
import type { Request } from '../../contract/types.ts'
import { day, inr, time } from './format.ts'

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]!))

export function openReceipt(r: Request) {
  const b = r.booking
  if (!b) return
  const who = r.shortlist.find((s) => s.expert_id === b.expert_id)
  const bookedAt = [...r.timeline].reverse().find((e) => e.step === 'BOOKED')?.t ?? b.start
  const mins = Math.round((+new Date(b.end) - +new Date(b.start)) / 60000)
  const claims = (who?.claims ?? []).map((c) =>
    `<li><b>${esc(c.status)}</b>: ${esc(c.text)}${c.evidence ? `<br><span class="m">${esc(c.evidence)} (${esc(c.source)})</span>` : ''}</li>`).join('')
  const rows: [string, string][] = [
    ['Receipt no.', `SUT-${esc(r.id)}`],
    ['Booked on', `${day(bookedAt)}, ${time(bookedAt)}`],
    ['Expert', `${esc(who?.name ?? b.expert_id)}${who?.headline ? `<br><span class="m">${esc(who.headline)}</span>` : ''}`],
    ['Call', `${day(b.start)}, ${time(b.start)} – ${time(b.end)} (${mins} min, IST)`],
    ['Calendar event', `<code>${esc(b.calendar_event_id)}</code>`],
    ['Your request', `“${esc(r.raw_text)}”`],
  ]
  if (r.constraints) rows.push(['Budget limit', inr(r.constraints.max_inr)])

  const html = `<!doctype html><html><head><meta charset="utf-8"><title>Receipt ${esc(r.id)} · Sutradhar</title>
<style>
  *{box-sizing:border-box} body{font-family:Inter,system-ui,Segoe UI,sans-serif;color:#111;margin:0;background:#f4f4f5}
  .p{max-width:720px;margin:32px auto;background:#fff;border:1px solid #e4e4e7;border-radius:16px;padding:40px}
  .h{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:2px solid #111;padding-bottom:18px;margin-bottom:22px}
  .brand{font-size:22px;font-weight:700;letter-spacing:-.02em} .m{color:#71717a;font-size:13px}
  .paid{background:#dcfce7;color:#166534;font-weight:700;font-size:12px;padding:4px 10px;border-radius:999px;letter-spacing:.06em}
  table{width:100%;border-collapse:collapse;font-size:14px} td{padding:10px 0;border-bottom:1px solid #f0f0f0;vertical-align:top} td:first-child{color:#71717a;width:170px}
  .tot{display:flex;justify-content:space-between;align-items:center;margin-top:22px;padding:18px;background:#fafafa;border-radius:12px}
  .tot b{font-size:28px} h3{font-size:14px;margin:26px 0 8px} ul{margin:0;padding-left:18px;font-size:13px;line-height:1.6}
  .f{margin-top:28px;font-size:12px;color:#a1a1aa;text-align:center} button{margin:0 auto 24px;display:block;padding:10px 18px;border-radius:999px;border:0;background:#111;color:#fff;font-weight:600;cursor:pointer}
  @media print{body{background:#fff}.p{border:0;margin:0}button{display:none}}
</style></head><body>
<div class="p">
  <div class="h"><div><div class="brand">Sutradhar</div><div class="m">Verified expert calls</div></div>
  <div style="text-align:right"><span class="paid">CONFIRMED</span><div class="m" style="margin-top:8px">${esc(b.confirmation)}</div></div></div>
  <table>${rows.map(([k, v]) => `<tr><td>${k}</td><td>${v}</td></tr>`).join('')}</table>
  <div class="tot"><span>Total for this call</span><b>${inr(b.price_inr)}</b></div>
  ${claims ? `<h3>Verification of this expert</h3><ul>${claims}</ul>` : ''}
  <div class="f">Booking summary generated by Sutradhar. Not a tax invoice.</div>
</div>
<button onclick="print()">Print / Save as PDF</button>
</body></html>`

  const w = window.open('', '_blank')
  if (!w) { alert('Please allow pop-ups to open the receipt.'); return }
  w.document.open(); w.document.write(html); w.document.close()
}
